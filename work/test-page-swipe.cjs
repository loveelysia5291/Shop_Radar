const fs = require('fs');
const assert = require('node:assert/strict');
const gesture = fs.readFileSync('app/src/main/java/com/aykkdk/shop/PageSwipeGesture.kt', 'utf8');
const main = fs.readFileSync('app/src/main/java/com/aykkdk/shop/MainActivity.kt', 'utf8');
assert(gesture.includes('pager.scroll(MutatePriority.UserInput)'));
assert(gesture.includes('for (delta in events)'));
assert(gesture.includes('intent.dragStartDelta'));
assert(gesture.includes('boundedScroll.performFling'));
assert(gesture.includes('events.cancel()'));
assert(gesture.includes('dragEvents?.close()'));
assert(!gesture.includes('animateScrollToPage'));
assert(!gesture.includes('tween('));
assert(gesture.includes('WindowInsets.systemGestures'));
assert(gesture.includes('systemGestures.getLeft(density, layoutDirection)'));
assert(gesture.includes('systemGestures.getRight(density, layoutDirection)'));
assert(gesture.indexOf('PageSwipeEdgePolicy.canStart') < gesture.indexOf('val intent = PageSwipeIntent'));
assert(!gesture.includes('systemGestureExclusion'));
const pagerBlock = main.slice(main.indexOf('HorizontalPager(pager'), main.indexOf('val modifier = Modifier.fillMaxSize().padding(horizontal = 16.dp)', main.indexOf('HorizontalPager(pager')));
assert(pagerBlock.includes('pager = pager, fling = pageFling'));
assert(!pagerBlock.includes('!pager.isScrollInProgress'));
assert(!pagerBlock.includes('animateScrollToPage'));
assert(main.includes('pager.animateScrollToPage(i, animationSpec = tween(300))'));
console.log('PASS: continuous drag and native fling; direction gate retained; no release-only tween or self-cancelling scroll key; bottom-tab animation unchanged.');
