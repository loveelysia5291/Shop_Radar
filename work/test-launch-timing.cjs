const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = path => fs.readFileSync(path, 'utf8');
const root = 'app/src/main/';
const main = read(root + 'java/com/aykkdk/shop/MainActivity.kt');
const launch = read(root + 'java/com/aykkdk/shop/LaunchAnimation.kt');
const manifest = read(root + 'AndroidManifest.xml');
const activity = main.slice(main.indexOf('class MainActivity'), main.indexOf('private fun RadarApp'));
assert.match(activity, /setContent \{ RadarLaunchHost\(savedInstanceState == null, nativeReady = launchWindowDismissed\) \{ RadarApp\(/);
assert.match(activity, /if \(Build.VERSION.SDK_INT >= 31\) \{\s*splashScreen.setOnExitAnimationListener/);
assert.match(activity, /splash.remove\(\)\s*launchWindowDismissed = true/);
assert.match(activity, /launchWindowDismissed by mutableStateOf\(Build.VERSION.SDK_INT < 31\)/);
assert.doesNotMatch(main, /LaunchAnimation\(animateLaunch\)/);
assert.match(launch, /if \(contentReady\) content\(\)/);
assert.match(launch, /LaunchedEffect\(view, nativeReady\)[\s\S]*?if \(launchVisible && nativeReady\) \{\s*awaitLaunchDraw\(view\)\s*animationReady = true/);
assert.match(launch, /LaunchedEffect\(view, contentReady\)[\s\S]*?awaitLaunchDraw\(view\)\s*contentDrawn = true/);
assert.match(launch, /LaunchAnimation\(launchVisible, animationReady, contentDrawn, onEntranceFinished = \{ contentReady = true \}\)/);
assert.match(launch, /scale.animateTo\(1f, tween\(360\)\)\s*entranceFinished\(\)/);
assert.match(launch, /LaunchedEffect\(contentDrawn\) \{\s*if \(contentDrawn\) visible = false/);
assert.match(launch, /remember \{ Animatable\(0.82f\) \}/);
assert.match(launch, /observer\.addOnDrawListener\(listener\)/);
assert.match(launch, /if \(!posted\) \{ posted = true; view\.post\(release\) \}/);
assert.match(launch, /continuation\.invokeOnCancellation/);
assert.match(launch, /view\.removeCallbacks\(release\); removeListener\(\)/);
assert.match(launch, /var contentReady by remember \{ mutableStateOf\(!launchVisible\) \}/);
assert.match(launch, /enabled && motionEnabled/);
const waiter = launch.slice(launch.indexOf('private suspend fun awaitLaunchDraw'), launch.indexOf('/** Vector-only entrance'));
assert.doesNotMatch(waiter, /delay\(|Thread\.sleep|canSearch|WorkManager|CookieManager|fetch|loadUrl/);
const cookies = main.match(/LaunchedEffect\(foreground, menu\) \{[\s\S]*?(?=LaunchedEffect\(pager.targetPage)/)?.[0];
assert.match(cookies, /if \(foreground && menu\)/);
assert.doesNotMatch(cookies, /delay\(300\)/);
assert.match(manifest, /android:name="\.MainActivity"[\s\S]{0,160}android:theme="@style\/Theme.ShopRadar.Launch"/);
assert.equal((manifest.match(/E?:?activity android:name="\.MainActivity"/g) || []).length, 1);
assert.doesNotMatch(manifest, /SplashActivity|LaunchActivity/);
const base = read(root + 'res/values/themes.xml');
assert.match(base, /name="Theme.ShopRadar.Launch"[\s\S]*?windowBackground">@color\/launch_background/);
const native = read(root + 'res/values-v31/launch.xml');
assert.match(native, /windowSplashScreenAnimatedIcon">@drawable\/launch_empty_icon/);
assert.match(native, /windowSplashScreenBackground">@color\/launch_background/);
assert.doesNotMatch(native, /windowSplashScreenBrandingImage/);
assert.equal(fs.existsSync(root + 'res/drawable/launch_background.xml'), false, 'No full-size static logo before entrance');
const empty = read(root + 'res/drawable/launch_empty_icon.xml');
assert.match(empty, /<vector/);
assert.match(empty, /fillColor="#00000000"/);
assert.doesNotMatch(empty, /ic_brand_mark|ic_launcher/);
assert.match(read(root + 'res/values-night/launch.xml'), /#10141C/);
assert.match(launch, /tween\(360\)/);
assert.doesNotMatch(launch, /delay\(|withFrameNanos|animateFloatAsState/);
assert.match(launch, /fadeOut\(tween\(180\)\)/);
console.log('PASS: background-only native splash, one logo animation after native exit/actual draw, stores created after entrance, fade after content draw, cancellation and reduced-motion paths; no duplicate static logo or fixed hold. Android device visual QA remains required.');
