const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = 'app/src/main/java/com/example/shopradar/';
const main = fs.readFileSync(root + 'MainActivity.kt', 'utf8');
const capture = fs.readFileSync(root + 'MarketplaceCapture.kt', 'utf8');
const search = main.match(/LaunchedEffect\(fetching, searchToken\)[\s\S]*?(?=LaunchedEffect\(showSearchResults)/)[0];
assert.equal((search.match(/val started = SystemClock.elapsedRealtime\(\)/g) || []).length, 1);
assert.match(search, /elapsed >= SearchWaitPolicy\.SLOW_MILLIS/);
assert.match(search, /!SearchPageLoading.infinite\(market\) && elapsed >= SearchPageLoading\.deadline\(count, market\)/);
assert.doesNotMatch(search, /CaptureBudgets\.waitForReader/);
assert.match(search, /SearchPageLoading.infinite\(market\) && count == 0 &&[\s\S]*?SearchPageLoading.emptyDeadline\(market, true\)/);
assert.doesNotMatch(search, /retryAttempt = 1|web\.reload|queue = arrayListOf\(Market\.RUTEN/);
assert.match(capture, /feedEnd.observe/);
assert.match(capture, /feedEnd.stalled/);
assert.doesNotMatch(search, /searchMillis|25_000|20_000|delay\(15000/);
assert.match(search, /products\.addAll\(stagedProducts\.distinctBy/);
assert.match(main, /backgroundCapture == capture && capture\.token == searchToken && fetching/);
assert.match(capture, /if \(navigation\.isForMainFrame\) \{[\s\S]{0,140}HTTP \$\{response\.statusCode\}[\s\S]{0,60}immediate = true/);
assert.match(capture, /error\.errorCode == WebViewClient\.ERROR_TIMEOUT/);
assert.match(capture, /handler\.cancel\(\)[\s\S]{0,150}immediate = true/);
assert.match(capture, /if \(immediate\) \{[\s\S]{0,220}onTimeout\(message\)[\s\S]{0,30}return/);
assert.match(main, /LaunchedEffect\(subscriptionShopToken\)[\s\S]*?elapsed >= SearchWaitPolicy\.SLOW_MILLIS[\s\S]*?showSubscriptionProducts = true/);
assert.match(main, /previewOnlyProducts && showSubscriptionProducts\) subscriptionProducts = shopPreviewStaged\.toList\(\)/);
assert.match(main, /fetching = previewOnlyProducts && subscriptionShopSearching/);
assert.match(main, /!showNewItemsPage && !showSubscriptionProducts/);
assert.match(main, /shopPreview = preview/);
assert.match(capture, /!request\.quickSearch && !request\.shopPreview && !request\.scanSubscription/);
const settings = fs.readFileSync(root + 'BackgroundDeliverySettings.kt', 'utf8');
assert.match(settings, /ACTION_APPLICATION_DETAILS_SETTINGS/);
assert.doesNotMatch(settings, /ACTION_IGNORE_BATTERY_OPTIMIZATION_SETTINGS|ACTION_REQUEST_IGNORE_BATTERY_OPTIMIZATIONS|startService|setComponent|su\b|Runtime\.getRuntime/);
assert.match(settings, /runCatching \{ context\.startActivity\(intent\)/);
const manifest = fs.readFileSync('app/src/main/AndroidManifest.xml', 'utf8');
assert.doesNotMatch(manifest, /REQUEST_IGNORE_BATTERY_OPTIMIZATIONS|SCHEDULE_EXACT_ALARM|FOREGROUND_SERVICE/);
console.log('PASS: mobile empty deadline and continuous stream, numbered-page completion gate, stale callbacks guarded, immediate main HTTP/SSL failures, store preview and background permissions preserved.');
