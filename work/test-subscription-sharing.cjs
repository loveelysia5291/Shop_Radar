const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require('C:/Users/Elysia/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const read = name => fs.readFileSync('app/src/main/java/com/aykkdk/shop/'+name, 'utf8');
const source = fs.readFileSync('app/src/main/assets/extract-shopee-products.js', 'utf8');
(async () => {
  const browser = await chromium.launch({channel:'msedge', headless:true});
  try {
    const page = await browser.newPage();
    await page.route('**/*', route => route.fulfill({contentType:'text/html; charset=utf-8', body:'<meta charset="utf-8"><article style="height:120px"><a href="/product/161121855/24672618478"><h3>華碩手機維修</h3><span>$1000</span></a></article>'}));
    await page.goto('https://shopee.tw/tanyulin704080');
    assert.equal(JSON.parse(await page.evaluate(source)).length, 0, 'Unknown username routes are not ordinary search surfaces');
    await page.evaluate(()=>{window.__shopRadarShopeeStoreUrl='https://shopee.tw/tanyulin704080';});
    let products=JSON.parse(await page.evaluate(source));
    assert.equal(products.length,1,'The exact native-selected public store can expose its product cards');
    assert.equal(products[0].title,'華碩手機維修');
    await page.evaluate(()=>{window.__shopRadarShopeeStoreUrl='https://shopee.tw/other_store';});
    assert.equal(JSON.parse(await page.evaluate(source)).length,0,'Another store does not satisfy the requested store');
    await page.goto('https://shopee.tw/login');
    await page.evaluate(()=>{window.__shopRadarShopeeStoreUrl=location.href;});
    assert.equal(JSON.parse(await page.evaluate(source)).length,0,'Native flags never authorize private pages');
    const manifest=fs.readFileSync('app/src/main/AndroidManifest.xml','utf8');
    assert.match(manifest,/android\.intent\.action\.SEND/);
    assert.match(manifest,/android:mimeType="text\/plain"/);
    assert.match(manifest,/android:launchMode="singleTask"/);
    assert.match(manifest,/android:documentLaunchMode="never"/);
    const main=read('MainActivity.kt');
    assert.match(main,/intent\.removeExtra\(Intent\.EXTRA_TEXT\)/);
    assert.match(main,/sharedSubscription\.takeIf \{ pager\.settledPage == 1 \}/);
    assert.match(main,/SubscriptionImporter\.add\(context, input\)/);
    const importer=read('SubscriptionImporter.kt');
    assert.ok(importer.indexOf('RefreshKind.AUCTION) {') < importer.indexOf('store.addPublicUrl(clean, initial)'), 'Auction branch executes before any product insertion');
    assert.match(importer,/require\(snapshot\?\.auctionTypeKnown == true\)/);
    const store=read('ProductSubscriptions.kt');
    assert.equal((store.match(/SubscriptionRefreshQueue\.request\(context, RefreshTarget\(RefreshKind\.PRODUCT, url\)\)/g)||[]).length,2,'Both search cards and raw URL imports trigger their first refresh');
    const queue=read('SubscriptionRefreshQueue.kt');
    assert.match(queue,/if \(target\.key in jobs\) return/);
    const web=read('PublicProductWebReader.kt');
    assert.match(web,/withTimeoutOrNull\(15_000\)/);
    assert.match(web,/sameProductUrl\(final, original\)/);
    assert.match(web,/handler\.cancel\(\)/);
    assert.match(web,/view\.destroy\(\)/);
    const shopStart=main.indexOf('items(shops,');
    const productStart=main.indexOf('items(productSubscriptions,');
    assert.doesNotMatch(main.slice(shopStart, productStart),/刷新這件商品/);
    assert.match(main.slice(productStart),/刷新這件商品/);
    console.log('PASS: official username store scope, sharing entry/recreation guard, shared importer, auction-first routing, initial per-target refresh, product-only refresh button, bounded final-route reader.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
